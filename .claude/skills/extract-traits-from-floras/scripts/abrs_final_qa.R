suppressPackageStartupMessages({library(dplyr);library(stringr);library(readr)})
n <- read_csv("data/ABRS_2026/data.csv", col_types = cols(.default = "c"))
cat("rows", nrow(n), " taxa", n_distinct(n$taxon_name), " families", n_distinct(n$family), "\n")
new <- n %>% filter(family %in% strsplit(readLines(file.path(Sys.getenv("S"), "fams.txt")), ",")[[1]])
cat("new-family rows", nrow(new), " taxa", n_distinct(new$taxon_name), "\n"); print(new %>% group_by(family) %>% summarise(taxa = n_distinct(taxon_name), rows = n()))
keys <- c("taxon_name","commonness_qualifier","leaf_division","entity_measured","population_region","plant_organ_measured","trait_scoring_method")
cat("dup keys:", sum(duplicated(n[keys])), "\n")
chr <- n %>% select(where(is.character)) %>% as.matrix()
cat("digit-hyphen-digit cells:", sum(str_detect(chr, "[0-9]\\s*[-–]\\s*[0-9]"), na.rm = TRUE), "  empty-set marker:", sum(str_detect(chr, "∅"), na.rm = TRUE), "\n")
for (t in c("flowering_time","fruiting_time")) cat(t, "bad length:", sum(!is.na(n[[t]]) & nchar(n[[t]]) != 12), "\n")
tr <- names(yaml::read_yaml("config/traits.yml")$traits$elements)
cols <- names(n); base <- unique(str_remove(cols, "_(description|min|max|extreme_min|extreme_max)$"))
mapped <- base[paste0(base, "_description") %in% cols | paste0(base, "_min") %in% cols | paste0(base, "_max") %in% cols]
cat("trait-like columns not in traits.yml:", paste(setdiff(mapped, tr), collapse = ", "), "\n")
