suppressPackageStartupMessages({library(traits.build); library(dplyr)})
schema <- get_schema(); resource_metadata <- get_schema("config/metadata.yml", "metadata")
definitions <- get_schema("config/traits.yml", "traits"); unit_conversions <- get_unit_conversions("config/unit_conversions.csv")
taxon_list <- read_csv_char("config/taxon_list.csv")
cfg <- dataset_configure("data/NHNSW_2026/metadata.yml", definitions)
raw <- dataset_process("data/NHNSW_2026/data.csv", cfg, schema, resource_metadata, unit_conversions)
x <- dataset_update_taxonomy(raw, taxon_list)
cat("traits rows", nrow(x$traits), " taxa", n_distinct(x$traits$taxon_name), " traits", n_distinct(x$traits$trait_name), "\n")
ex <- x$excluded_data
cat("excluded rows", nrow(ex), "\n"); print(ex %>% count(error, sort = TRUE) %>% head(10))
print(ex %>% count(trait_name, error, sort = TRUE) %>% head(15))
cat("unmatched taxa:", sum(is.na(x$taxa$taxon_rank) | !x$taxa$taxon_name %in% taxon_list$taxon_name), "\n")
print(ex %>% select(taxon_name, trait_name, value, unit) %>% as.data.frame())
um <- x$taxa %>% filter(!taxon_name %in% taxon_list$taxon_name) %>% pull(taxon_name)
print(um)
print(x$taxonomic_updates %>% filter(original_name != aligned_name | is.na(taxon_name)) %>% select(original_name, aligned_name, taxon_name) %>% head(30) %>% as.data.frame())
