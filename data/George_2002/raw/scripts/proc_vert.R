# Process George_2002 with traits.build (dataset_process): checks the metadata maps cleanly and counts excluded values (2026-11-09)
suppressPackageStartupMessages({library(traits.build); library(dplyr); library(stringr)})
schema <- get_schema(); resource_metadata <- get_schema("config/metadata.yml", "metadata")
definitions <- get_schema("config/traits.yml", "traits"); unit_conversions <- get_unit_conversions("config/unit_conversions.csv")
cfg <- dataset_configure("data/George_2002/metadata.yml", definitions)
x <- dataset_process("data/George_2002/data.csv", cfg, schema, resource_metadata, unit_conversions)
cat("George_2002", nrow(x$traits), "rows", n_distinct(x$traits$taxon_name), "taxa", n_distinct(x$traits$trait_name), "traits\n")
print(x$excluded_data %>% count(error, sort = TRUE), n = 30)
print(x$excluded_data %>% count(trait_name, error, sort = TRUE), n = 30)
print(x$excluded_data %>% filter(!str_detect(error, "^Unsupported trait value")) %>% count(trait_name, value, error, sort = TRUE) %>% head(40), n = 40)
saveRDS(x$traits, "ignore/jobs/vert1/traits_George_2002.rds")
