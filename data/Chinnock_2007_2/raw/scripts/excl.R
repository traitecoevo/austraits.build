suppressPackageStartupMessages({library(traits.build); library(dplyr); library(readr)})
schema <- get_schema(); resource_metadata <- get_schema("config/metadata.yml", "metadata")
definitions <- get_schema("config/traits.yml", "traits"); unit_conversions <- get_unit_conversions("config/unit_conversions.csv")
cfg <- dataset_configure("data/Chinnock_2007_2/metadata.yml", definitions)
x <- dataset_process("data/Chinnock_2007_2/data.csv", cfg, schema, resource_metadata, unit_conversions)
d <- read_csv("data/Chinnock_2007_2/data.csv", show_col_types = FALSE, col_types = cols(.default = "c"))
e <- x$excluded_data %>% filter(error != "Observation excluded in metadata") %>% distinct(taxon_name, trait_name, value, error)
dd <- d %>% distinct(taxon_name, trait_name, value_description)
out <- e %>% left_join(dd, by = c("taxon_name", "trait_name"), relationship = "many-to-many") %>% group_by(taxon_name, trait_name, value, error) %>% slice(1) %>% ungroup()
write_csv(out, "ignore/jobs/erem1/excluded.csv")
print(out %>% transmute(taxon_name = substr(taxon_name, 1, 28), trait_name = substr(trait_name, 1, 24), value, vd = substr(value_description, 1, 60)), n = 70, width = 200)
